"""Generates src/RosterControl.Desktop/Styles/Icons.axaml from Lucide SVGs (ISC license).

Run: python tools/generate_lucide_icons.py
Each SVG element (path, circle, rect, line, polyline, polygon, ellipse) is converted to SVG path data
so the icons can be stroked by the LucideIcon control at any size.
"""
import re, sys, urllib.request, xml.etree.ElementTree as ET

VERSION = "1.77.0"
ICONS = """plus minus x trash-2 search star swords shield crosshair notebook-pen tag download upload folder-open refresh-cw chevron-down chevron-right
chevron-left chevron-up pencil copy ellipsis layers users user target sparkles check settings panel-left arrow-left grip-vertical layout-grid list
info triangle-alert circle-check gem coins book-open thumbs-up thumbs-down flame zap database archive sliders-horizontal funnel eye eye-off
circle-x arrow-up-down arrow-down-wide-narrow map scroll-text heart crown move external-link save rotate-ccw circle-help square-pen list-ordered
shopping-bag wand-sparkles skull trophy book-marked hand-metal shield-half sword clipboard-list library-big minimize-2 maximize-2 monitor keyboard hard-drive bold list-checks share-2 clipboard-paste
""".split()

NS = "{http://www.w3.org/2000/svg}"

def f(v): return float(v)

def fmt(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"

def absolute_start(d):
    """SVG treats a path's leading 'm' as absolute (and its extra pairs as relative 'l'). Because all elements are
    joined into one path, make that explicit; otherwise the move becomes relative to the previous element's end."""
    d = d.strip()
    if not d.startswith("m"): return d
    m = re.match(r"m([^a-zA-Z]*)(.*)", d, re.S)
    nums = re.findall(r"-?\d*\.?\d+(?:e-?\d+)?", m.group(1))
    rest = m.group(2)
    head = f"M{nums[0]} {nums[1]}"
    if len(nums) > 2: head += " l" + " ".join(nums[2:])
    return head + rest

def convert(el):
    tag = el.tag.replace(NS, "")
    a = el.attrib
    if tag == "path": return absolute_start(a["d"])
    if tag == "circle":
        cx, cy, r = f(a["cx"]), f(a["cy"]), f(a["r"])
        return f"M{fmt(cx-r)} {fmt(cy)}a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2*r)} 0a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2*r)} 0Z"
    if tag == "ellipse":
        cx, cy, rx, ry = f(a["cx"]), f(a["cy"]), f(a["rx"]), f(a["ry"])
        return f"M{fmt(cx-rx)} {fmt(cy)}a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2*rx)} 0a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2*rx)} 0Z"
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{pts[i]} {pts[i+1]}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y, w, h = f(a.get("x", 0)), f(a.get("y", 0)), f(a["width"]), f(a["height"])
        rx = f(a.get("rx", a.get("ry", 0)))
        ry = f(a.get("ry", rx))
        if rx == 0:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        return (f"M{fmt(x+rx)} {fmt(y)}h{fmt(w-2*rx)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(ry)}v{fmt(h-2*ry)}"
                f"a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(ry)}h{fmt(-(w-2*rx))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(-ry)}"
                f"v{fmt(-(h-2*ry))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(-ry)}Z")
    return ""

out = ['<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
       f'  <!-- Generated by tools/generate_lucide_icons.py from lucide-static@{VERSION} (ISC License, https://lucide.dev). Do not edit. -->']
missing = []
for name in ICONS:
    url = f"https://unpkg.com/lucide-static@{VERSION}/icons/{name}.svg"
    try:
        svg = urllib.request.urlopen(url, timeout=20).read().decode("utf8")
    except Exception as e:
        missing.append(name); continue
    root = ET.fromstring(svg)
    parts = [convert(el) for el in root.iter() if el is not root]
    data = " ".join(p for p in parts if p)
    out.append(f'  <StreamGeometry x:Key="Icon.{name}">{data}</StreamGeometry>')
out.append("</ResourceDictionary>")
open(sys.argv[1] if len(sys.argv) > 1 else "src/RosterControl.Desktop/Styles/Icons.axaml", "w", encoding="utf8").write("\n".join(out) + "\n")
print("missing:", missing)
